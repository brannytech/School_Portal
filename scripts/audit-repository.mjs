// Read-only schema/content inventory. Never emits account details, secrets or student records.
import fs from 'node:fs';
import path from 'node:path';
import {DatabaseSync} from 'node:sqlite';
import {curriculum} from '../curriculum.mjs';

fs.mkdirSync('docs',{recursive:true});
const excluded=new Set(['.git','.snapshots','node_modules','data','data-production','backups','test-results','dist']);
function tree(directory='',indent=''){
 return fs.readdirSync(directory||'.',{withFileTypes:true}).filter(e=>!excluded.has(e.name)&&!e.name.startsWith('.env')).sort((a,b)=>a.name.localeCompare(b.name)).flatMap(e=>{
  const name=path.join(directory,e.name);
  return [indent+e.name+(e.isDirectory()?'/':''),...(e.isDirectory()?tree(name,indent+'  '):[])];
 });
}
const file=path.resolve(process.env.DATA_DIR||'data','school.sqlite');
if(!fs.existsSync(file))throw Error('No existing SQLite database; run against an explicit existing DATA_DIR.');
const sql=new DatabaseSync(file,{readOnly:true});
try{
 const tables=sql.prepare("SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all();
 const schema=tables.map(({name,sql:definition})=>({name,definition,columns:sql.prepare(`PRAGMA table_info(${name})`).all(),foreignKeys:sql.prepare(`PRAGMA foreign_key_list(${name})`).all(),rows:sql.prepare(`SELECT COUNT(*) AS count FROM ${name}`).get().count}));
 const counts={topics:curriculum.length,lessons:curriculum.reduce((n,w)=>n+w.lessons.length,0),lessonQuestions:curriculum.reduce((n,w)=>n+w.lessons.reduce((a,l)=>a+l.questions.length,0),0),masteryQuestions:curriculum.reduce((n,w)=>n+w.quiz.length,0)};
 const inventory={date:new Date().toISOString(),runtime:process.version,driver:'SQLite (read-only inspection)',migrations:sql.prepare('SELECT version,applied_at FROM schema_migrations ORDER BY version').all(),integrity:sql.prepare('PRAGMA quick_check').all(),foreignKeyViolations:sql.prepare('PRAGMA foreign_key_check').all(),seededCurriculum:counts,schema};
 fs.writeFileSync('docs/BASELINE_INVENTORY.json',JSON.stringify(inventory,null,2)+'\n');
 fs.writeFileSync('docs/REPOSITORY_TREE.md','# Repository inventory — 21 October 2026\n\nGenerated by `node --experimental-sqlite scripts/audit-repository.mjs`. Private data, secrets, dependencies, generated builds, test artifacts and Git internals are excluded.\n\n```text\n'+tree().join('\n')+'\n```\n');
 console.log(JSON.stringify({tables:schema.length,integrity:inventory.integrity,foreignKeyViolations:inventory.foreignKeyViolations.length,seededCurriculum:counts}));
}finally{sql.close();}
